/**
 * Retrieve persisted language code from localStorage, falling back to 'en'.
 */
export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'es' || saved === 'fr' || saved === 'en') {
      return saved
    }
  } catch (_e) {
    // localStorage may be disabled or inaccessible
  }
  return 'en'
}

/**
 * Translate a dot-notation key (e.g. 'settings.title').
 * Falls back to English, and if still missing, returns fallback or key.
 * Never returns undefined, never crashes.
 */
export function translate(lang, key, params = null, fallback = null) {
  const currentLang = (lang === 'es' || lang === 'fr') ? lang : 'en'
  const keys = key ? key.split('.') : []

  let val = translations[currentLang]
  for (const k of keys) {
    if (val && typeof val === 'object' && k in val) {
      val = val[k]
    } else {
      val = undefined
      break
    }
  }

  // Fallback to English if not found in current language
  if (val === undefined && currentLang !== 'en') {
    let enVal = translations.en
    for (const k of keys) {
      if (enVal && typeof enVal === 'object' && k in enVal) {
        enVal = enVal[k]
      } else {
        enVal = undefined
        break
      }
    }
    val = enVal
  }

  if (val === undefined || typeof val !== 'string') {
    val = fallback !== null && fallback !== undefined ? fallback : key
  }

  // Parameter interpolation: {name}
  if (params && typeof params === 'object') {
    for (const [pKey, pVal] of Object.entries(params)) {
      val = val.replaceAll(`{${pKey}}`, pVal ?? '')
    }
  }

  return val
}
